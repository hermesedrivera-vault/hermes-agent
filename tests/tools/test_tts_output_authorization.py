"""Phase 12.1 (Step 9 Phase 3 -> Step 10 -> Step 10.1 -> Step 11 ->
Step 12.1 authorization/security boundary implementation): TTS output
authorization.

Verifies that every TTS filesystem write -- explicit model-supplied
output_path AND the default auto-generated audio_cache path alike --
passes through the canonical Phase-3 general file-write authorization
primitive (``tools.file_tools._check_general_file_write``), and that an
existing file at the target path is NEVER deleted, truncated, or
otherwise destructively overwritten regardless of the authorization
outcome.

Uses the command-provider TTS backend (a portable ``python -c`` copy
command, same technique as test_tts_command_providers.py) so these tests
exercise the real _text_to_speech_single()/text_to_speech_tool() code
paths end-to-end without touching a real network TTS API.
"""

