class TestExistingFileNeverDestroyed:
    """The core Phase 12.1 fix: an existing file at the target is never
    deleted or truncated, regardless of whether authorization is granted
    or denied."""

    def test_existing_target_survives_denial(self, tmp_path, approvals):
        target = tmp_path / "existing.mp3"
        target.write_bytes(b"PRE-EXISTING AUDIO BYTES")
        approvals["answer"] = "deny"
        res = _run_tts("hello", str(target))
        assert not res.get("success"), res
        assert target.read_bytes() == b"PRE-EXISTING AUDIO BYTES", (
            "existing file must be byte-for-byte unchanged on denial"
        )

    def test_existing_target_survives_approval_via_free_path(self, tmp_path, approvals):
        """When authorization is GRANTED for a path that already has a
        file, the write must never clobber that file -- it must resolve
        to a new, non-colliding sibling path instead (matching Flux's
        _free_path pattern), per the Step 12.1 explicit requirement that
        authorization alone does not make destructive overwrite safe."""
        target = tmp_path / "existing.mp3"
        target.write_bytes(b"PRE-EXISTING AUDIO BYTES")
        approvals["answer"] = "once"
        res = _run_tts("hello", str(target))
        assert res.get("success"), res
        assert target.read_bytes() == b"PRE-EXISTING AUDIO BYTES", (
            "existing file must never be silently overwritten even when "
            "the write is approved"
        )
        written_path = res["file_path"]
        assert os.path.abspath(written_path) != os.path.abspath(str(target)), (
            "the actual write must land on a resolved sibling path, not "
            "the original occupied target"
        )
        assert os.path.isfile(written_path)


