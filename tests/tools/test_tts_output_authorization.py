class TestFinalResolvedPathMatchesAuthorizedPath:
    def test_authorized_path_is_exactly_the_written_path(self, tmp_path, approvals, monkeypatch):
        """The authorization decision must correspond to the EXACT path
        that ends up on disk -- never a further-transformed path."""
        captured = {}
        from tools import file_tools as ft
        original = ft._check_general_file_write

        def spy(paths, task_id="default"):
            captured["paths"] = list(paths)
            return original(paths, task_id)

        monkeypatch.setattr(ft, "_check_general_file_write", spy)
        # tts_tool imports the function locally inside _tts_authorize_destination,
        # so patch the source module -- the local `from tools.file_tools import
        # _check_general_file_write` re-resolves it from tools.file_tools each call.
        approvals["answer"] = "once"
        target = tmp_path / "match_check.mp3"
        res = _run_tts("hello", str(target))
        assert res.get("success"), res
        assert captured.get("paths") == [res["file_path"]], (
            "the path passed to the authorization primitive must be "
            "identical to the path actually written"
        )


class TestEveryBackendCovered:
    """Every TTS backend receives its path from the single choke point in
    _text_to_speech_single()/text_to_speech_tool() -- this class asserts
    that invariant directly rather than re-testing each backend's network
    call, which the existing provider-specific test files already mock
    and cover independently (test_tts_speed.py, etc.)."""

    def test_synthesize_with_command_provider_no_longer_deletes(self, tmp_path):
        """Direct regression test for the removed unlink(): calling the
        command-provider backend on an existing target must not delete
        it as a side effect of the backend itself (that responsibility
        now lives entirely in the caller's pre-authorized _tts_free_path
        resolution, never in this function)."""
        from tools.tts_tool import _generate_command_tts
        target = tmp_path / "backend_direct.mp3"
        target.write_bytes(b"SENTINEL")
        config = {
            "command": _python_copy_command(),
            "output_format": "mp3",
        }
        # Feed the backend a *different*, non-colliding path (as the
        # caller now always does) -- confirms the backend itself performs
        # no existence check/deletion of its own.
        other = tmp_path / "backend_direct-2.mp3"
        _generate_command_tts(
            "hello", str(other), "my-command-tts", config, {},
        )
        assert target.read_bytes() == b"SENTINEL", (
            "the command-provider backend must never touch an unrelated "
            "existing file"
        )
        assert other.exists()

    def test_single_chunk_helper_forwards_task_id(self, tmp_path, approvals, monkeypatch):
        """_text_to_speech_single accepts and uses task_id for scope-correct
        authorization -- NeuTTS and every other backend inherit this via
        the same single path-resolution point, so this one test covers
        the invariant for all of them."""
        monkeypatch.setattr("tools.tts_tool._load_tts_config", lambda: _command_tts_config())
        monkeypatch.setattr("gateway.session_context.get_session_env", lambda *a, **k: "")
        approvals["answer"] = "once"
        target = tmp_path / "task_scoped.mp3"
        raw = _text_to_speech_single(
            "hello", str(target), tts_config_override=_command_tts_config(),
            task_id="my-task-42",
        )
        res = json.loads(raw)
        assert res.get("success"), res


class TestSessionTaskSubagentAuthorizationScope:
    """Mirrors tests/tools/test_authorization_scope_phase3.py's task
    isolation guarantee, applied to the TTS gate specifically."""

    def test_grant_under_one_task_does_not_satisfy_another_task(self, tmp_path, approvals, monkeypatch):
        import tools.approval as A
        monkeypatch.setattr("tools.tts_tool._load_tts_config", lambda: _command_tts_config())
        monkeypatch.setattr("gateway.session_context.get_session_env", lambda *a, **k: "")

        session_key = A.get_current_session_key()
        tokens_a = A.set_current_authorization_scope(session_key, task_id="task-A")
        approvals["answer"] = "once"
        target_a = tmp_path / "task_a.mp3"
        try:
            res_a = json.loads(_text_to_speech_single(
                "hello", str(target_a), tts_config_override=_command_tts_config(),
                task_id="task-A",
            ))
        finally:
            A.reset_current_authorization_scope(tokens_a)
        assert res_a.get("success"), res_a

        tokens_b = A.set_current_authorization_scope(session_key, task_id="task-B")
        approvals["answer"] = "deny"
        target_b = tmp_path / "task_b.mp3"
        try:
            res_b = json.loads(_text_to_speech_single(
                "hello", str(target_b), tts_config_override=_command_tts_config(),
                task_id="task-B",
            ))
        finally:
            A.reset_current_authorization_scope(tokens_b)
        assert not res_b.get("success"), (
            "a grant scoped to task-A must not satisfy a write requested "
            "under task-B"
        )
