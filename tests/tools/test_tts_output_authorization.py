def _run_tts(text, output_path, **kw):
    with pytest.MonkeyPatch.context() as mp:
        mp.setattr("tools.tts_tool._load_tts_config", lambda: _command_tts_config())
        mp.setattr("gateway.session_context.get_session_env", lambda *a, **k: "")
        raw = text_to_speech_tool(text, output_path=output_path, **kw)
    return json.loads(raw)


class TestExplicitOutputPathAuthorization:
    def test_explicit_output_path_requests_approval(self, tmp_path, approvals):
        approvals["answer"] = "once"
        target = str(tmp_path / "narration.mp3")
