from tools.tts_tool import text_to_speech_tool, _text_to_speech_single


def _python_copy_command() -> str:
    interpreter = sys.executable
    return (
        f'"{interpreter}" -c "import shutil, sys; '
        f'shutil.copyfile(sys.argv[1], sys.argv[2])" '
        f'{{input_path}} {{output_path}}'
    )


def _command_tts_config():
    return {
        "provider": "my-command-tts",
        "providers": {
            "my-command-tts": {
                "type": "command",
                "command": _python_copy_command(),
                "output_format": "mp3",
            },
        },
    }


